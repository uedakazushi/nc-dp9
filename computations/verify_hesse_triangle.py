#!/usr/bin/env python3
"""Exact finite checks for Hesse-Kodaira--Spencer and triangle affine group (v18).
Checks symbolic commutators, character weights and translation congruences;
not a machine proof of AS regularity or deformation unobstructedness.
"""
from itertools import product
import sympy as s


def verify_hesse():
    x,y,z,u,v=s.symbols('x y z u v')
    f=u*x*y*z+v*(x**3+y**3+z**3)/3
    assert s.diff(f,x)==u*y*z+v*x*x
    assert s.diff(f,y)==u*z*x+v*y*y
    assert s.diff(f,z)==u*x*y+v*z*z
    # Diagonal action d=(1,zeta,zeta^2) preserves each relation subspace.
    relations=[[(('y','z'),1),(('z','y'),1),(('x','x'),1)],
               [(('z','x'),1),(('x','z'),1),(('y','y'),1)],
               [(('x','y'),1),(('y','x'),1),(('z','z'),1)]]
    weights={'x':0,'y':1,'z':2}
    for idx,rel in enumerate(relations):
        residues={(weights[a]+weights[b])%3 for ((a,b),coef) in rel}
        assert residues=={[0,2,1][idx]}
    # Cyclic automorphism permutes relation spaces.
    rotate={'x':'y','y':'z','z':'x'}
    for idx,rel in enumerate(relations):
        nxt=[((rotate[a],rotate[b]),coeff) for ((a,b),coeff) in rel]
        assert nxt==relations[(idx+1)%3]
    monomials=[(i,j,3-i-j) for i in range(4) for j in range(4-i)]
    fixed_d=[e for e in monomials if (e[1]+2*e[2])%3==0]
    # cyclic group acts on x^3, y^3, z^3 as a 3-cycle, fixing xyz
    assert set(fixed_d)=={(3,0,0),(0,3,0),(0,0,3),(1,1,1)}
    assert len(monomials)==10
    # KS classes of two independent parameters are xyz, sum cubes.
    assert s.Poly(s.diff(f,u),x,y,z)!=s.Poly(s.diff(f,v),x,y,z)
    assert s.Poly(s.diff(f,u),x,y,z).monoms()==[(1,1,1)]
    assert len(s.Poly(s.diff(f,v),x,y,z).monoms())==3
    print('PASS Hesse cyclic potential, Heisenberg weights, 2 independent KS parameters')


def verify_triangle():
    eye=s.eye(3)
    F01=s.diag(-1,-1,1)
    F12=s.diag(1,-1,-1)
    F02=s.diag(-1,1,-1)
    e0,e1,e2=[s.eye(3)[:,i] for i in range(3)]
    A=(F01,e0); B=(F12,e1); C=(F02,e2)
    def mul(a,b):return a[0]*b[0],a[0]*b[1]+a[1]
    def sq(a):return mul(a,a)
    def vec(v):return tuple(map(int,v))
    assert all(M==eye and vec(t)==(0,0,0) for (M,t) in (sq(A),sq(B),sq(C)))
    generators=[A,B,C]
    assert vec(sq(mul(A,B))[1])==(0,-2,0)
    assert vec(sq(mul(B,C))[1])==(0,0,-2)
    assert vec(sq(mul(C,A))[1])==(-2,0,0)
    assert vec(mul(mul(A,B),C)[1])==(1,-1,-1)
    assert mul(mul(A,B),C)[0]==eye
    assert F01*F12*F02==eye
    # All affine translations with trivial sign part found in bounded words
    # are in parity lattice. Conversely 2ei and (1,-1,-1) generate it.
    words=[(eye,s.zeros(3,1))]
    holonomies=set()
    for length in range(1,9):
        words=[mul(g,a) for g in words for a in generators]
        for M,t in words:
            if M==eye:
                coords=vec(t)
                assert len({q%2 for q in coords})==1
            holonomies.add(tuple(M.diagonal()))
        assert len(holonomies)<=4
    assert len(holonomies)==4
    # Index 4 sublattice generated by 2e0,2e1,2e2,(1,-1,-1)
    mat=s.Matrix.hstack(2*e0,2*e1,2*e2,e0-e1-e2)
    from sympy.matrices.normalforms import hermite_normal_form
    h=hermite_normal_form(mat)
    assert h.det()==4
    for vec3 in product(range(-3,4),repeat=3):
        same=len({p%2 for p in vec3})==1
        coeff=h.inv()*s.Matrix(vec3)
        assert same==all(x.q==1 for x in coeff)
    print('PASS triangle affine group, rank-3 translation lattice index 4, parity invariants')


if __name__=='__main__':
    verify_hesse()
    verify_triangle()
    print('Finite calculations passed; existence/coherence of categorical roots is not certified.')
